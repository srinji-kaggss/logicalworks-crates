//! Source-visible deterministic simulation replay cases.
//!
//! The wider simulation families declare their bands through a macro, so Nextest
//! sees hundreds of replayed cases while a source-level audit only sees the few
//! literal `#[test]` attributes. This target keeps that audit honest without
//! weakening the simulation contract: every case below is a real test attribute
//! in a `sim_*` file, and every one drives the same seeded harness twice,
//! through a real `Bot`, real `MemoryJournal`, virtual time and the faulted
//! network, then compares the trace hash.

use crate::sim;

use std::error::Error;

use sim::rig::Run;

/// Test result type shared by the generated source-visible cases.
type TestResult = Result<(), Box<dyn Error>>;

/// Runs one source-visible deterministic replay case.
fn replay_seed(seed: u64) -> TestResult {
    sim::assert_replays(sim::Band::new(seed, 1), |sim| {
        let run = Run::new();
        let before = run.recorded()?.len();
        run.lands()?.tick()?;
        let after = run.recorded()?.len();
        assert!(
            after > before,
            "seed {seed} did not drive the real bot journal forward: {before} then {after}"
        );
        assert_eq!(
            run.entered(),
            1,
            "seed {seed} must run the real effect body exactly once"
        );

        let tenants = sim.faults.tenants.max(1);
        let recipient = sim.rng().between(0, tenants.saturating_sub(1));
        let payload = u8::try_from(sim.rng().below(251))?;
        let delay = u64::from(sim.rng().between(0, 7));
        let due = sim.clock.now().saturating_add(delay);
        sim.send(0, recipient, vec![payload], due);
        let delivered = sim.advance_and_drain(delay);
        for envelope in &delivered {
            assert_eq!(
                envelope.from(),
                0,
                "seed {seed} delivered an envelope from the wrong tenant"
            );
            assert_eq!(
                envelope.body(),
                &[payload],
                "seed {seed} delivered a payload the sender did not put on the wire"
            );
            sim.trace
                .record_number("delivered-to", u64::from(envelope.to()));
            sim.trace
                .record_number("delivery-attempts", u64::from(envelope.attempts()));
        }
        let (delivered_count, dropped_count, duplicate_count) = sim.net.counts();
        sim.record("source-visible-simulation-replayed");
        sim.trace.record_number("journal-events", after);
        sim.trace
            .record_number("network-delivered", u64::from(delivered_count));
        sim.trace
            .record_number("network-dropped", u64::from(dropped_count));
        sim.trace
            .record_number("network-duplicated", u64::from(duplicate_count));
        Ok(())
    })
}

/// Declares cases with source-visible `#[test]` attributes.
macro_rules! source_visible_cases {
    ($(#[$attr:meta] $name:ident => $seed:literal;)+) => {
        $(
            #[doc = "Source-visible deterministic simulation replay case."]
            #[$attr]
            fn $name() -> TestResult {
                replay_seed($seed)
            }
        )+
    };
}

