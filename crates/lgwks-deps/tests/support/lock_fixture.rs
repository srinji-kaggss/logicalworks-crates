//! A `Cargo.lock` and a scratch repository to put it in, for tests that drive
//! the shipped binary.
//!
//! The lock is written the way Cargo writes it: a generated-file header,
//! `version = 4`, one `[[package]]` block per package separated by a blank line,
//! and the `dependencies` array one quoted entry per line. A workspace member
//! has no `source`; a registry package has a `source` and a `checksum`.

use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use lgwks_std::{hex, random};

/// crates.io's source, in the spelling Cargo writes for the git index.
pub const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// One locked package.
///
/// The fields are private: a test builds a package through a constructor that
/// names what kind it is, and cannot assemble one that is a registry package in
/// one field and a workspace member in another.
#[derive(Debug, Clone)]
pub struct Package {
    /// The package name.
    name: String,
    /// The resolved version.
    version: String,
    /// The `source` key, or `None` for a workspace member or a path dependency.
    source: Option<String>,
    /// The `dependencies` entries, as the lock writes them.
    dependencies: Vec<String>,
}

impl Package {
    /// A workspace member.
    pub fn local(name: &str, dependencies: &[&str]) -> Self {
        Self {
            name: name.to_owned(),
            version: "0.1.0".to_owned(),
            source: None,
            dependencies: owned(dependencies),
        }
    }

    /// A package from crates.io.
    pub fn registry(name: &str, version: &str, dependencies: &[&str]) -> Self {
        Self::from_source(name, version, CRATES_IO, dependencies)
    }

    /// A package from the registry or repository `source` names.
    pub fn from_source(name: &str, version: &str, source: &str, dependencies: &[&str]) -> Self {
        Self {
            name: name.to_owned(),
            version: version.to_owned(),
            source: Some(source.to_owned()),
            dependencies: owned(dependencies),
        }
    }
}

/// The entries as owned strings.
fn owned(entries: &[&str]) -> Vec<String> {
    entries.iter().map(|entry| (*entry).to_owned()).collect()
}

/// The text of a `Cargo.lock` holding `packages`, in order.
pub fn render(packages: &[Package]) -> Result<String, Box<dyn Error>> {
    let mut text = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n",
    );
    for package in packages {
        writeln!(text, "\n[[package]]")?;
        writeln!(text, "name = \"{}\"", package.name)?;
        writeln!(text, "version = \"{}\"", package.version)?;
        if let Some(source) = package.source.as_deref() {
            writeln!(text, "source = \"{source}\"")?;
            writeln!(text, "checksum = \"{}\"", "0".repeat(64))?;
        }
        if !package.dependencies.is_empty() {
            writeln!(text, "dependencies = [")?;
            for entry in &package.dependencies {
                writeln!(text, " \"{entry}\",")?;
            }
            writeln!(text, "]")?;
        }
    }
    Ok(text)
}

/// A scratch directory under the OS temp root, removed when the test ends.
///
/// RAII rather than a cleanup call at the end of the test body: the assertions
/// that fail are exactly the runs that must not leave the directory behind.
pub struct Scratch {
    /// The directory this guard owns.
    path: PathBuf,
}

impl Scratch {
    /// Creates `<temp>/lgwks-deps-<tag>-<nonce>`, empty.
    ///
    /// The tag is per test, so two tests never share a directory and a stale one
    /// from an earlier run cannot change a verdict.
    pub fn new(tag: &str) -> Result<Self, Box<dyn Error>> {
        let nonce = hex::encode(random::bytes::<8>()?);
        let path = std::env::temp_dir().join(format!("lgwks-deps-{tag}-{nonce}"));
        if path.exists() {
            std::fs::remove_dir_all(&path)?;
        }
        std::fs::create_dir_all(&path)?;
        Ok(Self { path })
    }

    /// The directory this guard owns.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Writes `packages` as the `Cargo.lock` of a repository at `repo/` in this
    /// directory, and returns that root.
    pub fn write_lock(&self, packages: &[Package]) -> Result<PathBuf, Box<dyn Error>> {
        let root = self.path.join("repo");
        std::fs::create_dir_all(&root)?;
        std::fs::write(root.join("Cargo.lock"), render(packages)?)?;
        Ok(root)
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        // Best effort: the tree is this process's own, below the OS temp root,
        // and a leftover directory is not a reason to fail a test that has
        // already decided its verdict.
        if std::fs::remove_dir_all(&self.path).is_err() {
            // Nothing to report here; `Drop` has no failure channel.
        }
    }
}
