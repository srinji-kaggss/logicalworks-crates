/// The second task's oracle. Its first clause (libtest runs clauses by name, and
/// `announce` sorts first) does nothing unless the gate names a listener; then it
/// announces its process id and blocks reading from the connection, with a bounded
/// read so a runner that fails to stop it cannot park the suite.
pub(super) const BETA_ORACLE: &str = r##"use ai_trial::double;
use std::io::{Read, Write};
use std::process;

#[test]
fn announce_then_block_when_asked() -> Result<(), Box<dyn std::error::Error>> {
    let Some(address) = std::env::var_os("__GATE__") else {
        return Ok(());
    };
    let mut stream = std::net::TcpStream::connect(address.to_string_lossy().as_ref())?;
    // The id is what the test inspects (`ps`) to prove this very process is gone,
    // not a name this process keys anything by.
    writeln!(stream, "{}", process::id())?;
    stream.flush()?;
    stream.set_read_timeout(Some(std::time::Duration::from_secs(__VALVE__)))?;
    let mut byte = [0_u8; 1];
    let _ended = stream.read(&mut byte);
    writeln!(stream, "VALVE")?;
    Ok(())
}

#[test]
fn doubles() -> Result<(), String> {
    if double(21) == 42 { Ok(()) } else { Err(format!("double was {}", double(21))) }
}

#[test]
fn dropping_leaves_nothing_live() -> Result<(), String> {
    if ai_task_support::nothing_live() { Ok(()) } else { Err("something is live".to_owned()) }
}
"##;

